export type Language = 'vi' | 'en' | 'ja' | 'ko' | 'zh' | 'es' | 'fr' | 'de' | 'pt' | 'it';

export const SUPPORTED_LANGUAGES: { code: Language; label: string; flag: string }[] = [
  { code: 'vi', label: 'Tiếng Việt', flag: '🇻🇳' },
  { code: 'en', label: 'English', flag: '🇺🇸' },
  { code: 'ja', label: '日本語', flag: '🇯🇵' },
  { code: 'ko', label: '한국어', flag: '🇰🇷' },
  { code: 'zh', label: '中文', flag: '🇨🇳' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
  { code: 'fr', label: 'Français', flag: '🇫🇷' },
  { code: 'de', label: 'Deutsch', flag: '🇩🇪' },
  { code: 'pt', label: 'Português', flag: '🇧🇷' },
  { code: 'it', label: 'Italiano', flag: '🇮🇹' },
];

export function detectUserLanguage(): Language {
  try {
    const saved = localStorage.getItem('app_user_lang') as Language | null;
    if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
    const browserLangs = navigator.languages || [navigator.language || 'en'];
    for (const langStr of browserLangs) {
      const code = langStr.toLowerCase().split('-')[0] as Language;
      if (SUPPORTED_LANGUAGES.some((l) => l.code === code)) {
        return code;
      }
    }
  } catch (e) {
    console.warn('Could not detect language automatically', e);
  }
  return 'en';
}

